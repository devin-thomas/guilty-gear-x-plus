int DZBitHoming(CHARACTER_WORK *offset) {
    CHARACTER_WORK *poffset;
    int targetx;
    int targety;

    poffset = offset->parentWork;
    targetx = poffset->posx + GetXMove(offset, 7000) - offset->posx;
    targety = poffset->posy - 15000 - offset->posy + G_Sin((offset->ActTimer & 0x7F) << 9) * 80.0f * 100.0f;
    if (abs(targetx) > 400) {
        if (targetx < 0) {
            offset->xspeed -= 100;
        } else {
            offset->xspeed += 100;
        }
        offset->xspeed -= offset->xspeed / 10;
    } else {
        offset->xspeed -= offset->xspeed / 10;
        if (abs(offset->xspeed) < 20) {
            offset->xspeed = 0;
        }
    }
    if (abs(targety) > 400) {
        if (targety < 0) {
            offset->yspeed -= 75;
        } else {
            offset->yspeed += 75;
        }
        offset->yspeed -= offset->yspeed / 10;
    } else {
        offset->yspeed -= offset->yspeed / 10;
        if (abs(offset->yspeed) < 20) {
            offset->yspeed = 0;
        }
    }
    return abs(targetx) + abs(targety);
}

void DZBT_ColliCheck(CHARACTER_WORK *offset) {
    CHARACTER_WORK *poffset;

    poffset = offset->parentWork;
    if (offset->actno < 12) {
        if (offset->actno != 10 && g_info.boss[poffset->padid] == 1) {
            if (poffset->actst & 0x20) {
                SetActNoNext(offset, 10);
                return;
            }
            if (BattleStatus != 2) {
                SetActNoNext(offset, 10);
                return;
            }
        }
        if (offset->HitColliFlag) {
            offset->HitStopTime = 26;
        }
        if (offset->DamColliFlag) {
            RequestHit(offset, offset->DamActHeader[0].flag, offset->DamActHeader[0].lvflag, 0);
            SetAttackActNo(offset, 10);
        }
    }
}

void SetBitAlive(CHARACTER_WORK *offset) {
    CHARACTER_WORK *poffset;

    poffset = offset->parentWork;
    poffset->ply->ObjFlag |= 2;
    offset->Localid++;
    if (offset->actno != 10) {
        if (GetBattleTimeStopFlag(-1)) {
            SetActNoNext(offset, 10);
        } else if (poffset->HitPoint <= 0) {
            SetActNoNext(offset, 10);
        }
    }
}

void DZBTSetActNext(CHARACTER_WORK *offset) {
    CHARACTER_WORK *poffset;
    CHARACTER_WORK *eoffset;
    RECTL *p;
    int i;

    poffset = offset->parentWork;
    eoffset = poffset->ply->Enemy;
    if (!IsActEnd(offset)) {
        return;
    }
    if (g_info.boss[poffset->padid] == 1) {
        if (eoffset->posx < offset->posx) {
            offset->dirflag = 0;
        } else {
            offset->dirflag = 1;
        }
        if (BattleStatus != 2) {
            SetActNoNext(offset, 10);
        }
        p = GetScreenRect();
        if (offset->posx >= p->x + p->w + 10000) {
            SetActNoNext(offset, 10);
            return;
        }
        if (offset->posx <= p->x - 10000) {
            SetActNoNext(offset, 10);
            return;
        }
        if (offset->posy <= p->y - 10000) {
            SetActNoNext(offset, 10);
            return;
        }
    }
    if (poffset->actno == 0x62 || poffset->actno == 0x9C || poffset->actno == 0x9D ||
        poffset->actno == 0x9E || poffset->actno == 0x9F) {
        SetActNoNext(offset, 10);
        return;
    }
    for (i = 0; i < 4; i++) {
        int dat = poffset->ply->PersonalWork[0].b[i];

        poffset->ply->PersonalWork[0].b[i] = 0;
        switch (dat) {
        case 0:
            break;
        case 1:
            SetActNoNext(offset, 2);
            return;
        case 2:
            SetActNoNext(offset, 4);
            return;
        case 3:
            SetActNoNext(offset, 6);
            return;
        case 4:
            SetActNoNext(offset, 8);
            return;
        case 5:
            SetActNoNext(offset, 1);
            return;
        }
    }
    if (g_info.boss[poffset->padid] == 1) {
        SetActNoNext(offset, 1);
        return;
    }
    SetActNoNext(offset, 10);
}

