void DZBTAct_Wait(CHARACTER_WORK *offset) {
    CHARACTER_WORK *poffset;
    int i;

    poffset = offset->parentWork;
    SetBitAlive(offset);
    SetChangeFrameAnimeSameActno(offset);
    offset->dirflag = poffset->dirflag;
    DZBitHoming(offset);
    if (g_info.boss[poffset->padid] == 1) {
        for (i = 0; i < 4; i++) {
            int dat = poffset->ply->PersonalWork[0].b[i];

            if (BattleStatus != 2) {
                SetActNoNext(offset, 10);
                continue;
            }
            switch (dat) {
            case 0:
                break;
            case 1:
                SetActNoNext(offset, 2);
                poffset->ply->PersonalWork[0].b[i] = 0;
                i = 4;
                break;
            case 2:
                SetActNoNext(offset, 4);
                poffset->ply->PersonalWork[0].b[i] = 0;
                i = 4;
                break;
            case 3:
                SetActNoNext(offset, 6);
                poffset->ply->PersonalWork[0].b[i] = 0;
                i = 4;
                break;
            case 4:
                SetActNoNext(offset, 8);
                poffset->ply->PersonalWork[0].b[i] = 0;
                i = 4;
                break;
            case 5:
                break;
            }
        }
    }
    SetJumpControl(offset);
    if (GetPlayerDist() < 30000) {
        SetActNoNext(offset, 6);
    }
}

