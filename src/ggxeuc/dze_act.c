void DZBTAct_SHW1_HomingLaser(CHARACTER_WORK *offset)
{
    int last;
    if (SetChangeFrameAnimeSameActno(offset)) {
        offset->angle = (offset->Localid & 0xFF) << 8;
        offset->actwork.w[0] = 2500;
    }
    SetJumpControl(offset);
    LandtoEliminate(offset);
    SetXSpeed(offset, -G_Sin(offset->angle) * offset->actwork.w[0]);
    SetYSpeed(offset, -G_Cos(offset->angle) * offset->actwork.w[0], 0);
    if (!IsHitStop(offset)) {
        if (offset->actwork.w[0] >= 1000 || !(offset->ActTimer & 1)) {
            CREATE_ARG c_arg;
            c_arg.flag = 0x1000;
            c_arg.angle = offset->angle;
            EffectCreate_ActNo(offset, 0x43, &c_arg, 0x2D);
        }
    }
    if (offset->attackst & 0x1000) {
        if (offset->actwork.w[0] < 4000) offset->actwork.w[0] += 100;
        OutSideEliminate(offset);
        if (offset->Localid & 0x100) {
            CHARACTER_WORK *enemy = GetEnemyPlayer(offset);
            enemy->actst |= 8;
            SearchCharacterExecute(enemy, 0x43, 0x2C, 0x17);
        }
        return;
    } else last = (u_short)offset->angle;
    /* SCHED_BARRIER: empty volatile asm, emits nothing. It keeps the `last` load out of the
       GetEnemyPlayer sched block so `li rst,1` lands in the jal delay slot as in the original. */
    __asm__ volatile ("");
    {
        int low, high;
        int x, y;
        int rst = 1;
        CHARACTER_WORK *enemy;

        enemy = GetEnemyPlayer(offset);
        x = enemy->posx - offset->posx;
        if (offset->ActTimer < 8) {
            y = -18000 - offset->posy;
        } else if (SearchCharacterExecute(enemy, 0x43, 0x2C, 7)) {
            y = offset->posy + 18000;
            y = enemy->posy - y;
        } else {
            y = offset->posy + 10000;
            y = enemy->posy - y;
        }
        low = high = GetAngle_xy(offset, x, -y);
        while (last < low) low -= 0x10000;
        while (high < last) high += 0x10000;
        low = ABS(low - last);
        high = ABS(high - last);
        if (high < low) {
            if (high > 0x400) {
                offset->angle += 0x400;
                rst = 0;
            }
        } else if (low > 0x400) {
            offset->angle -= 0x400;
            rst = 0;
        }
        if (offset->Localid & 0x200) {
            if (rst) {
                offset->actwork.w[0] = (offset->actwork.w[0] < 3800) ? offset->actwork.w[0] + 200 : 4000;
            } else if (offset->actwork.w[0] > 300) {
                offset->actwork.w[0] = offset->actwork.w[0] * 0.9;
            }
        } else if (offset->actwork.w[0] > 200) {
            offset->actwork.w[0] = offset->actwork.w[0] * 0.9;
        }
    }
}

