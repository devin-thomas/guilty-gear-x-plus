void VEMCAct_1(CHARACTER_WORK *offset) {
    int tb[8] = { 3, 4, 5, 6, 7, 3, 4, 5 };
    CREATE_ARG c_arg;

    if (g_info.mode & 0x4000) {
        set_random_seed_abs();
    }
    SetChangeFrameAnimeSameActno(offset);
    OutSideEliminate(offset);
    if (offset->actst & 0x80000000) {
        SearchCharacterExecute(offset, 0x32, 3, 0x16);
        SearchCharacterExecute(offset, 0x32, 4, 0x16);
        SearchCharacterExecute(offset, 0x32, 5, 0x16);
        SearchCharacterExecute(offset, 0x32, 6, 0x16);
        SearchCharacterExecute(offset, 0x32, 7, 0x16);
        return;
    }
    if (!IsHitStop(offset)) {
        if (EffectLiveCount < 80) {
            EffectCreate_ActNo(offset, 0x32, 0, tb[Random() & 7]);
        } else if (offset->ActTimer & 1) {
            EffectCreate_ActNo(offset, 0x32, 0, tb[Random() & 7]);
        }
        if ((!(offset->ActTimer & 3) && abs(offset->xspeed) > 900) ||
            (!(offset->ActTimer & 7) && abs(offset->xspeed) > 400)) {
            c_arg.flag = 5;
            c_arg.actno = 1;
            if (offset->dirflag) {
                c_arg.x = offset->posx + 6500;
            } else {
                c_arg.x = offset->posx - 6500;
            }
            c_arg.y = 0;
            EffectCreate(offset, 0x61, &c_arg);
        }
    }
    if (offset->Mark) {
        AddXSpeed(offset, 10);
    }
}

