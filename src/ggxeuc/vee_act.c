void VEBLHoming(CHARACTER_WORK *offset) {
    int targetx;
    int targety;
    float x;
    float y;
    float n;

    targetx = offset->HitBackx;
    targety = offset->RHitBackx;
    x = targetx - offset->posx;
    y = targety - offset->posy;
    n = nlSqrt(x * x + y * y);
    if (n < 300.0) {
        offset->HitPoint = 0;
    } else if (n < 1600.0) {
        offset->HitPoint = g_roundmin(offset->HitPoint - 100, 0);
    } else {
        offset->HitPoint = g_roundmax(offset->HitPoint + 60, 900);
    }
    offset->xspeed = x / n * offset->HitPoint;
    offset->yspeed = y / n * offset->HitPoint;
}

