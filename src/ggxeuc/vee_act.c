void VEBL_ColliCheck(CHARACTER_WORK *offset) {
    static unsigned char collibitfieldflag[] = { 0xE1, 0x03, 0x00, 0x00 };

    if (offset->actno == 0x1D) {
        if (offset->HitColliFlag) {
            EffectCreate_ActNo(offset, 0x32, 0, 0x1B);
            EffectCreate_ActNo(offset, 0x32, 0, 9);
            offset->actst |= 0x80000000;
        }
    } else if (offset->actno == 0x1B) {
        if (offset->HitColliFlag) {
            offset->Localid = 0xC0;
            offset->Mark = 1;
        }
    } else if (offset->actno == 0x1A) {
        if (offset->DamColliFlag) {
            SetActNo(offset, 0x1B);
            privatese_request(offset, 1);
            return;
        }
    } else if ((collibitfieldflag[offset->actno >> 3] >> (offset->actno & 7)) & 1) {
        if (offset->DamColliFlag) {
            SetActNo(offset, 1);
            privatese_request(offset, 1);
            return;
        }
    } else if (*(unsigned int *)&offset->ColliFlag & 0xFFFF00) {
        offset->xspeed = -offset->xspeed / 4;
        SetActNo(offset, 0x10004);
    }
}

void SetVallSpeed(CHARACTER_WORK *offset) {
    int angle;

    angle = (offset->Localid & 0xFF) << 8;
    SetXSpeed(offset, nlCos(angle) * offset->HitPoint * 100.0f);
    SetYSpeed(offset, nlSin(angle) * offset->HitPoint * 100.0f, 0);
    if (offset->CommandFlag & 4) {
        SetDamage(offset, offset->HitPoint / 4 + 20);
    } else if (offset->CommandFlag & 2) {
        SetDamage(offset, offset->HitPoint / 2 + 16);
    } else {
        SetDamage(offset, offset->HitPoint + 20);
    }
}

void SetItigekiVallSpeed(CHARACTER_WORK *offset) {
    int last;
    if (offset->InstSt & 0x20) {
        switch (offset->actno) {
        case 0x13: offset->Localid = 0x8000; break;
        case 0x14: offset->Localid = 0xA000; break;
        case 0x15: offset->Localid = 0x6000; break;
        case 0x16: offset->Localid = 0xC000; break;
        case 0x17: offset->Localid = 0x4000; break;
        case 0x18: offset->Localid = 0xE000; break;
        case 0x19: offset->Localid = 0x2000; break;
        case 0x1A: offset->Localid = 0; break;
        }
        offset->actwork.w[0] = 4000;
        do last = (u_short)offset->Localid; while (0);
    } else last = (u_short)offset->Localid;
    {
        int low, high;
        int x, y;
        int rst = 1;
        CHARACTER_WORK *enemy;

        enemy = GetEnemyPlayer(offset);
        x = enemy->posx - offset->posx;
        y = offset->posy - enemy->posy;
        high = low = GetAngle_xy(offset, x, y);
        while (last < low) low -= 0x10000;
        while (high < last) high += 0x10000;
        low = ABS(low - last);
        high = ABS(high - last);
        if (high > 0x500) {
            offset->Localid += 0x400;
            rst = 0;
        }
        if (IsActTimeOver(offset, offset->actno * 8 - 0x7A)) {
            if (rst) {
                if (offset->actwork.w[0] < 3800) offset->actwork.w[0] += 200;
                else offset->actwork.w[0] = 4000;
            } else if (offset->actwork.w[0] > 300) offset->actwork.w[0] = offset->actwork.w[0] * 0.9;
        } else if (offset->actwork.w[0] > 200) offset->actwork.w[0] = offset->actwork.w[0] * 0.9;
    }
    SetXSpeed(offset, -G_Sin(offset->Localid) * offset->actwork.w[0]);
    SetYSpeed(offset, -G_Cos(offset->Localid) * offset->actwork.w[0], 0);
}

