"""Compile the renderer's shaders for SDL_GPU and write dl_shaders.h (PORT-008).

    python build_shaders.py [--glslang <glslangValidator>] [--spirv-cross <spirv-cross>] [--dxc <dxc>]

Each GLSL shader becomes SPIR-V (Vulkan) with glslang; SPIRV-Cross turns the
SPIR-V into MSL (Metal) and into HLSL, which dxc compiles to DXIL (D3D12).
That is the route SDL_shadercross takes. The header holds all three as byte
arrays and is committed with the sources, so building the port needs none
of these tools; re-run this after editing a shader. Tested with MSYS2's
glslang 16.3 and SPIRV-Cross 1.4.357 and the Windows SDK's dxc 1.8.2502.

The sources use SDL_GPU's resource layout: vertex uniforms in set 1,
fragment samplers in set 2 and fragment uniforms in set 3. SPIRV-Cross maps
a set to an HLSL register space and keeps the bindings for MSL
(--msl-decoration-binding), which is what SDL_GPU expects of each.
"""
import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / 'dl_shaders.h'
SHADERS = [('draw.vert', 'vs'), ('draw.frag', 'ps'), ('full.vert', 'vs'), ('display.frag', 'ps')]


def find(name, given):
    if given:
        return given
    p = shutil.which(name)
    if p:
        return p
    for sdk in sorted(Path(r'C:\Program Files (x86)\Windows Kits\10\bin').glob('10.*'), reverse=True):
        c = sdk / 'x64' / (name + '.exe')
        if c.exists():
            return str(c)
    sys.exit(f'{name} not found; pass its path')


def run(args):
    r = subprocess.run([str(a) for a in args], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'failed: {" ".join(map(str, args))}\n{r.stdout}{r.stderr}')


def c_array(name, data):
    lines = [f'static const unsigned char {name}[{len(data)}] = {{']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--glslang')
    ap.add_argument('--spirv-cross', dest='spirv_cross')
    ap.add_argument('--dxc')
    a = ap.parse_args()
    glslang, spvc = find('glslangValidator', a.glslang), find('spirv-cross', a.spirv_cross)
    dxc = find('dxc', a.dxc)
    parts = ['/* Generated by build_shaders.py from the GLSL beside it. Do not edit. */',
             '#ifndef GGX_DL_SHADERS_H', '#define GGX_DL_SHADERS_H']
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for src, stage in SHADERS:
            name = src.replace('.', '_')
            spv, msl, hlsl, dxil = (tmp / f'{name}.{e}' for e in ('spv', 'msl', 'hlsl', 'dxil'))
            run([glslang, '-V', '--target-env', 'vulkan1.0', '-o', spv, HERE / src])
            run([spvc, '--msl', '--msl-version', '20100', '--msl-decoration-binding', '--output', msl, spv])
            run([spvc, '--hlsl', '--shader-model', '60', '--output', hlsl, spv])
            run([dxc, '-nologo', '-T', f'{stage}_6_0', '-E', 'main', '-O3', '-Fo', dxil, hlsl])
            parts.append(c_array(f'dl_{name}_spirv', spv.read_bytes()))
            parts.append(c_array(f'dl_{name}_msl', msl.read_bytes() + b'\0'))
            parts.append(c_array(f'dl_{name}_dxil', dxil.read_bytes()))
    parts.append('#endif')
    OUT.write_text('\n'.join(parts) + '\n', newline='\n')
    print(f'wrote {OUT.name}')


if __name__ == '__main__':
    main()
