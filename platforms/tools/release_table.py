#!/usr/bin/env python3
"""release_table.py --kr <image> --jp <image> -o common/assets/releases.c

Writes the table the port identifies the player's disc by: for each supported
release, every file in the disc's ISO 9660 tree with its LSN, size and SHA-256.
Names, numbers and hashes only: nothing from the files themselves.

<image> is an ISO (2048-byte sectors) or a raw BIN (2352-byte sectors), the
Redump dump of that release. Run it again only if a release is added.
"""
import argparse
import hashlib
import struct
from pathlib import Path

RELEASES = [
    # id, serial, title, boot ELF
    ('KR', 'SLPM-645.25', 'Guilty Gear X Plus (Korea)', 'SLPM_645.25'),
    ('JP', 'SLPS-201.37', 'Guilty Gear X Plus (Japan)', 'SLPS_201.37'),
]


class Image:
    def __init__(self, path):
        self.f = open(path, 'rb')
        self.f.seek(0, 2)
        size = self.f.tell()
        self.raw = False
        if size % 2352 == 0:
            self.f.seek(16 * 2352)
            self.raw = self.f.read(12) == b'\0' + b'\xff' * 10 + b'\0'

    def read(self, lsn, count=1):
        if not self.raw:
            self.f.seek(lsn * 2048)
            return self.f.read(count * 2048)
        out = []
        for i in range(count):
            self.f.seek((lsn + i) * 2352)
            s = self.f.read(2352)
            off = 24 if s[15] == 2 else 16
            out.append(s[off:off + 2048])
        return b''.join(out)


def walk(img, lsn, size, prefix, files):
    data = img.read(lsn, (size + 2047) // 2048)
    for s in range(0, len(data), 2048):
        o = s
        while o < s + 2048 and data[o]:
            r = data[o:o + data[o]]
            ext_lsn, ext_size, flags, n = struct.unpack_from('<I', r, 2)[0], struct.unpack_from('<I', r, 10)[0], r[25], r[32]
            name = r[33:33 + n]
            if not (n == 1 and name[0] <= 1):
                name = name.decode('ascii').split(';')[0].rstrip('.')
                if flags & 2:
                    walk(img, ext_lsn, ext_size, prefix + name + '/', files)
                else:
                    files.append((ext_lsn, ext_size, prefix + name))
            o += data[o]


def table(path):
    img = Image(path)
    pvd = img.read(16)
    assert pvd[0] == 1 and pvd[1:6] == b'CD001', f'{path}: no ISO 9660 volume'
    files = []
    walk(img, struct.unpack_from('<I', pvd, 158)[0], struct.unpack_from('<I', pvd, 166)[0], '', files)
    out = []
    for lsn, size, name in sorted(files):
        h = hashlib.sha256()
        left, at = size, lsn
        while left:
            chunk = img.read(at, min(512, (left + 2047) // 2048))[:left]
            h.update(chunk)
            left -= len(chunk)
            at += 512
        # the port's asset store reads the rest of a file's last sector as
        # zeros (common/assets/store.c), so the disc must hold zeros there
        if size % 2048:
            assert not img.read(lsn + size // 2048)[size % 2048:].strip(b'\0'), f'{name}: data after its end'
        out.append((name, lsn, size, h.hexdigest()))
    return out


ap = argparse.ArgumentParser()
ap.add_argument('--kr', required=True)
ap.add_argument('--jp', required=True)
ap.add_argument('-o', '--out', required=True)
a = ap.parse_args()

lines = ['/* The supported releases, by every file on their disc. Generated by',
         ' * tools/release_table.py from the Redump dumps: names, LSNs, sizes and',
         ' * SHA-256 only. */',
         '#include "releases.h"', '']
for rid, serial, title, boot in RELEASES:
    files = table(getattr(a, rid.lower()))
    names = [f[0] for f in files]
    assert boot in names, f'{rid}: no {boot} on the disc'
    lines.append(f'static const ReleaseFile files_{rid.lower()}[] = {{')
    for name, lsn, size, digest in files:
        lines.append(f'    {{ "{name}", {lsn}, {size}, "{digest}" }},')
    lines += ['};', '']
lines.append('const Release ggx_releases[GGX_RELEASES] = {')
for rid, serial, title, boot in RELEASES:
    lines.append(f'    {{ "{rid}", "{serial}", "{title}", "{boot}", files_{rid.lower()},')
    lines.append(f'      sizeof(files_{rid.lower()}) / sizeof(files_{rid.lower()}[0]) }},')
lines += ['};', '']
Path(a.out).write_text('\n'.join(lines), newline='\n')
