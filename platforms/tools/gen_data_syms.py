#!/usr/bin/env python3
"""gen_data_syms.py <symbol map> <out.c>: a weak placeholder for every PS2 data symbol.

Most of the game's data has no C definition: the matching build keeps it in
opaque bins, and the port loads it at run time from the player's own ELF.
The game C still names those symbols. This file gives each one a one-byte
weak definition so the Core links with undefined data treated as an error;
a real C definition wins over the placeholder. wasm_place.py then moves
every reference to the symbol's PS2 address, so the placeholders' bytes are
never used. Only names go in; no game data.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import symmap   # noqa: E402

# names wasm-ld defines itself
LINKER = {'__stack_pointer', '__heap_base', '__heap_end', '__data_end', '__dso_handle',
          '__global_base', '__memory_base', '__table_base', '__indirect_function_table'}


def main():
    m = symmap.SymbolMap(sys.argv[1])
    names = sorted({n for table in (m.globals, m.statics) for n, (_, is_func) in table.items()
                    if not is_func and n not in LINKER})
    out = ['/* Generated by platforms/tools/gen_data_syms.py. Do not edit. */\n']
    for k, name in enumerate(names):
        out.append(f'__attribute__((weak)) char ggx_ps2_data_{k}[1] __asm__("{name}");\n')
    data = ''.join(out)
    p = Path(sys.argv[2])
    if not p.exists() or p.read_text() != data:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(data, newline='\n')


if __name__ == '__main__':
    main()
