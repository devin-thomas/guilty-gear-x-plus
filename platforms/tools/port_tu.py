#!/usr/bin/env python3
"""port_tu.py <tu> <src.c> <out.c> --target kr|jp [--long64]: one game TU as the port compiles it.

The matching build never compiles a game file whole. build.py splits it with
scripts/csplit.py and compiles each function after the file's whole prelude
(every declaration, prototype and data definition in the file, in order).
So a function sees every prototype in its file, even one written below it.

The port compiles each TU once, so it rebuilds that view: the prelude in file
order, then a prototype for every function defined in the TU, then the
function bodies in file order, each marked `used` so none is dropped.
`#line` markers keep diagnostics and debug info pointing at the real source
lines. Nothing in src/ is changed.

The EE's `long` is 64 bits. Game TUs get that from `-Dlong=long long`;
--long64 instead spells each lone `long` as `long long` in the text, for TUs
that also write `long long` themselves (libgcc's), which the macro would make
`long long long long`. Either way an integer literal with one L suffix is
spelled with two (`0UL` -> `0ULL`): the macro can't reach a suffix.
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / 'scripts'))
import csplit       # noqa: E402
import sdkprofile   # noqa: E402


def chunks_with_lines(text):
    """(first line, chunk without its leading newlines, whole chunk) for each
    csplit chunk. The chunks are consecutive slices of `text`."""
    line = 1
    for ch in csplit._chunks(text):
        # a chunk usually starts with the newline that ended the last one
        lead = len(ch) - len(ch.lstrip('\n'))
        yield line + lead, ch[lead:], ch
        line += ch.count('\n')


def port_tu(tu, text, target, name):
    text = sdkprofile.source(tu, text, target)
    prelude, funcs = [], []
    skipped = True              # the next prelude chunk needs a #line marker
    for line, ch, whole in chunks_with_lines(text):
        _, fs = csplit.split(ch)
        mark = f'\n#line {line} "{name}"\n'
        if fs:
            funcs.append((fs[0][1], mark))
            skipped = True
        elif ch.strip():
            prelude.append(mark + ch if skipped else whole)
            skipped = False

    protos = []
    for ftext, _ in funcs:
        p = csplit.prototype(ftext)
        if re.search(r'\)\s*;$', p):    # old-style definitions have no prototype to copy
            protos.append(p)

    out = [f'/* Generated by platforms/tools/port_tu.py from {Path(name).name}. Do not edit. */']
    out += prelude
    out.append('\n#line 1 "<port_tu prototypes>"\n' + '\n'.join(protos) + '\n')
    # Many file statics are reached only through PS2 data (action and job
    # tables in the ELF image), which the compiler can't see; without `used`
    # it would drop them as dead.
    out += [mark + USED + ftext + '\n' for ftext, mark in funcs]
    return ''.join(out)


USED = '__attribute__((used)) '


def long64(text):
    """each lone `long` spelled `long long`"""
    text = re.sub(r'\blong\s+long\b', '@LL@', text)
    return re.sub(r'\blong\b', 'long long', text).replace('@LL@', 'long long')


LONG_LITERAL = re.compile(r'(?<![.\w])(0[xX][0-9A-Fa-f]+|[0-9]+)([uU]?)[lL]([uU]?)\b')


def long_literals(text):
    """each integer literal with one L suffix spelled with LL: `0UL` is 64 bits on the EE.
    (sprite.c's `tex & (~0UL >> 27)` keeps 37 bits of a GS TEX0 on the EE, 5 in a 32-bit long; PORT-006)"""
    return LONG_LITERAL.sub(lambda m: f'{m[1]}{m[2]}LL{m[3]}', text)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('tu')
    ap.add_argument('src', type=Path)
    ap.add_argument('out', type=Path)
    ap.add_argument('--target', choices=('kr', 'jp'), required=True)
    ap.add_argument('--long64', action='store_true')
    args = ap.parse_args()

    text = long_literals(args.src.read_text(encoding='utf-8'))
    if args.long64:
        text = long64(text)
    data = port_tu(args.tu, text, args.target, args.src.resolve().as_posix())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text(encoding='utf-8') != data:
        args.out.write_text(data, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
