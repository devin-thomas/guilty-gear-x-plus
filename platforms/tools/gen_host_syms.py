#!/usr/bin/env python3
"""gen_host_syms.py <symbol map> <statics map> <out.c>: PS2 names the native host needs, as C.

The host reads a few game variables by address (JobMode, jobfunc,
gsGParam, handle_list for the renderer, seekpos for the text layer,
pad_read_buf for the pad shim, mcPwd for the memory card shim, userinfo for the input layer's macros;
and, for which button confirms in menus, JobMode, Pause, sc, opt, tr_info, g_info, story and the statics
Pause_Execute.pos and Opt_KeyConfig's pos and btn, as ggx_static_<function>_<name>; for the unlocks (PORT-020),
LimitStatus and Opt_Password's passbuf, passidx and passmode) and names functions in its log (the job a field
runs). Both come
from the same symbol map wasm_place.py uses, so the host and the Core agree.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import symmap   # noqa: E402

NEEDED = ('JobMode', 'jobfunc', 'gsGParam', 'handle_list', 'seekpos', 'pad_read_buf', 'mcPwd', 'userinfo', 'Pause',
          'sc', 'opt', 'tr_info', 'g_info', 'story', 'LimitStatus')
NEEDED_STATICS = ('Pause_Execute.pos', 'Opt_KeyConfig.pos', 'Opt_KeyConfig.btn', 'Opt_Password.passbuf',
                  'Opt_Password.passidx', 'Opt_Password.passmode')


def main():
    m = symmap.SymbolMap(sys.argv[1])
    funcs = {}
    for name, (addr, is_func) in sorted(m.globals.items()):
        if is_func and not name.startswith('func_'):
            funcs.setdefault(addr, name)        # first name in sort order for aliases
    out = ['/* Generated by platforms/tools/gen_host_syms.py. Do not edit. */',
           '#include <stddef.h>', '#include <stdint.h>', '']
    for n in NEEDED:
        out.append(f'const uint32_t ggx_sym_{n} = 0x{m.globals[n][0]:08x}u;')
    statics = {}
    for line in Path(sys.argv[2]).read_text().splitlines():
        f = line.split()
        if len(f) == 3 and not line.startswith('#'):
            statics[f[1]] = int(f[2], 16)
    for n in NEEDED_STATICS:
        out.append(f"const uint32_t ggx_static_{n.replace('.', '_')} = 0x{statics[n]:08x}u;")
    out += ['', 'static const struct { uint32_t addr; const char *name; } FUNCS[] = {']
    out += [f'    {{ 0x{a:08x}u, "{n}" }},' for a, n in sorted(funcs.items())]
    out += ['};', '',
            'const char *ggx_func_name(uint32_t addr)',
            '{',
            '    size_t lo = 0, hi = sizeof(FUNCS) / sizeof(FUNCS[0]);',
            '',
            '    while (lo < hi) {',
            '        size_t mid = (lo + hi) / 2;',
            '        if (FUNCS[mid].addr < addr) {',
            '            lo = mid + 1;',
            '        } else {',
            '            hi = mid;',
            '        }',
            '    }',
            '    return lo < sizeof(FUNCS) / sizeof(FUNCS[0]) && FUNCS[lo].addr == addr ? FUNCS[lo].name : "?";',
            '}', '']
    data = '\n'.join(out)
    p = Path(sys.argv[3])
    if not p.exists() or p.read_text() != data:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(data, newline='\n')


if __name__ == '__main__':
    main()
